"""The ONNX backend must reproduce the vectors sentence-transformers produced.

#1070 replaced torch + sentence-transformers with ONNX Runtime to take 282 MB
compressed off the shared base image. That is only acceptable because the swap
runs the SAME weights through the SAME maths with a different kernel — so this
guards the one thing that would make it unacceptable: silently different vectors.

Golden vectors in tests/fixtures/embedding/ were generated by the OLD path
(sentence-transformers on model.safetensors) and are committed, so the check
needs neither torch nor the network. It does need the model, which is gitignored
(models/cache/), so it SKIPS where the model is absent — including CI.

That is why the same assertion also runs at image-build time in Dockerfile.base,
where the model is always present: a regression there fails the build. A skipped
test enforces nothing; the build-time gate is what makes this binding.

Tolerances come from measurement, not taste. Over 2000 real device strings the
worst observed cosine was 0.99999976 and max |abs diff| 1.132e-06, with identical
top-10 ordering on every one of 55 queries.
"""

import json
from pathlib import Path

import numpy as np
import pytest

FIXTURES = Path(__file__).resolve().parents[4] / 'tests' / 'fixtures' / 'embedding'
GOLDEN_VECTORS = FIXTURES / 'golden_vectors.npy'
GOLDEN_TEXTS = FIXTURES / 'golden_texts.json'

# Measured worst case is 2.4e-07 on this fixture set; 1e-5 leaves room for a
# different BLAS or CPU feature set without admitting a real regression.
MAX_ABS_DIFF = 1e-5
MIN_COSINE = 1 - 1e-6


def _backend():
    pytest.importorskip('onnxruntime')
    pytest.importorskip('tokenizers')
    from src.services.embedding.config import default_config
    from src.services.embedding.onnx_backend import OnnxTextEncoder, _snapshot_dir

    try:
        snap = _snapshot_dir(default_config.model_name, default_config.model_cache_path)
    except FileNotFoundError:
        pytest.skip('embedding model not present (models/cache is gitignored)')
    if not (snap / 'onnx' / 'model.onnx').exists():
        pytest.skip('ONNX export not present in the model cache')
    return OnnxTextEncoder(default_config.model_name, default_config.model_cache_path)


@pytest.fixture(scope='module')
def encoder():
    """One session for the whole module: constructing OnnxTextEncoder loads a
    436 MB graph, and doing that per test buys nothing."""
    return _backend()


@pytest.fixture(scope='module')
def golden():
    if not GOLDEN_VECTORS.exists():
        pytest.skip('golden vectors fixture missing')
    meta = json.loads(GOLDEN_TEXTS.read_text())
    return meta['texts'], np.load(GOLDEN_VECTORS)


def test_vectors_match_the_pre_swap_reference(encoder, golden):
    """The core guarantee: same text in, same vector out."""
    texts, expected = golden
    actual = encoder.encode(texts, normalize_embeddings=True)

    assert actual.shape == expected.shape
    max_diff = np.abs(actual - expected).max()
    cos = np.sum(actual * expected, axis=1)
    assert max_diff < MAX_ABS_DIFF, (
        f'ONNX vectors drifted from the sentence-transformers reference: '
        f'max |abs diff| {max_diff:.3e} >= {MAX_ABS_DIFF:.1e}. '
        'Embeddings feed semantic search; a drift here degrades retrieval silently.'
    )
    assert cos.min() > MIN_COSINE, f'worst cosine {cos.min():.12f} <= {MIN_COSINE}'


def test_ranking_is_preserved(encoder, golden):
    """What actually matters. Every embedding consumer is top-k ranking
    (chat tool routing, pipeline enrichment, suggestions, synonyms), so identical
    ORDER is the real acceptance criterion — a vector may differ in the last ulp
    provided no result reorders."""
    texts, expected = golden
    actual = encoder.encode(texts, normalize_embeddings=True)

    # Both similarity matrices once, not once per query.
    exp_sim, act_sim = expected @ expected.T, actual @ actual.T
    for i, text in enumerate(texts):
        exp_order = list(np.argsort(-exp_sim[i])[:10])
        act_order = list(np.argsort(-act_sim[i])[:10])
        assert exp_order == act_order, (
            f'top-10 ranking changed for query {i!r} ({text!r}):\n'
            f'  reference: {exp_order}\n  onnx:      {act_order}'
        )


def test_embeddings_are_l2_normalised(encoder, golden):
    """compute_similarity() takes a plain dot product when normalize_embeddings
    is set, so an unnormalised vector would silently produce wrong similarities
    rather than an error."""
    texts, _ = golden
    actual = encoder.encode(texts, normalize_embeddings=True)
    norms = np.linalg.norm(actual, axis=1)
    assert np.allclose(norms, 1.0, atol=1e-5), f'norms range {norms.min()}..{norms.max()}'


def test_normalisation_can_be_disabled(encoder, golden):
    texts, _ = golden
    raw = encoder.encode(texts[:4], normalize_embeddings=False)
    assert not np.allclose(np.linalg.norm(raw, axis=1), 1.0, atol=1e-3)


def test_batching_does_not_change_results(encoder, golden):
    """Padding is per batch, so a batch-size-dependent result would mean padding
    is leaking into the pooled vector."""
    texts, _ = golden
    one = encoder.encode(texts[:8], batch_size=1)
    many = encoder.encode(texts[:8], batch_size=8)
    assert np.abs(one - many).max() < 1e-5


def test_empty_input_returns_empty(encoder):
    assert encoder.encode([]).shape == (0,)


def test_pooling_mode_is_read_from_the_model_not_assumed(encoder):
    """Hardcoding CLS would produce wrong-but-plausible vectors if the model were
    ever swapped for a mean-pooling one."""
    assert encoder.pooling == 'cls'
