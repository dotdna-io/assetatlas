import json
import pytest
from pathlib import Path

SYNONYM_FILE = Path(__file__).parent.parent.parent / 'static' / 'synonym_lookup.json'


@pytest.fixture(scope='module')
def synonym_lookup():
    """Load the synonym lookup table."""
    if not SYNONYM_FILE.exists():
        pytest.skip('synonym_lookup.json not found - run scripts/generate_synonyms.py first')
    with open(SYNONYM_FILE) as f:
        return json.load(f)


