NEGATIVE_CASES = [
    ('name', 'hostname'),
    ('address', 'ip'),
    ('id', 'hostname'),
    ('type', 'category'),
    ('status', 'confidence_score'),
    ('version', 'os_normalized'),
]


class TestSynonymResolutionAccuracy:
    """Test that synonym lookup resolves common IT terms correctly."""

    def test_overall_accuracy_above_80_percent(self, synonym_lookup):
        """At least 80% of positive test cases must resolve correctly."""
        synonyms = synonym_lookup.get('synonyms', {})
        correct = 0
        total = len(POSITIVE_CASES)

        for term, expected_fields in POSITIVE_CASES:
            resolved = synonyms.get(term)
            if resolved and any(resolved == f or resolved.endswith(f) for f in expected_fields):
                correct += 1

        accuracy = correct / total if total > 0 else 0
        assert accuracy >= 0.80, (
            f"Synonym accuracy {accuracy:.1%} ({correct}/{total}) is below 80% threshold"
        )

    @pytest.mark.parametrize('term,expected_fields', POSITIVE_CASES)
    def test_positive_resolution(self, synonym_lookup, term, expected_fields):
        """Each positive case should resolve to one of the expected fields."""
        synonyms = synonym_lookup.get('synonyms', {})
        resolved = synonyms.get(term)
        if resolved is None:
            pytest.xfail(f'"{term}" not in synonym table - may need threshold tuning')
        matches = any(resolved == f or resolved.endswith(f) for f in expected_fields)
        assert matches, f'"{term}" resolved to "{resolved}", expected one of {expected_fields}'

    @pytest.mark.parametrize('term,wrong_field', NEGATIVE_CASES)
    def test_negative_resolution(self, synonym_lookup, term, wrong_field):
        """Negative cases should not resolve to the wrong field."""
        synonyms = synonym_lookup.get('synonyms', {})
        resolved = synonyms.get(term)
        if resolved is not None:
            assert not (resolved == wrong_field or resolved.endswith(wrong_field)), (
                f'"{term}" incorrectly resolved to "{resolved}" (matches "{wrong_field}")'
            )

    def test_metadata_present(self, synonym_lookup):
        """Lookup table should have valid metadata."""
        meta = synonym_lookup.get('_metadata', {})
        assert 'matched_terms' in meta
        assert meta['matched_terms'] >= 50
        assert 'total_fields' in meta
        assert meta['total_fields'] >= 20

    def test_minimum_term_coverage(self, synonym_lookup):
        """At least 50 terms should be resolved."""
        synonyms = synonym_lookup.get('synonyms', {})
        assert len(synonyms) >= 50, f'Only {len(synonyms)} synonyms - expected >=50'
