import { Modal } from '@/components/ui/Modal';
import type { FieldRegistryEntry } from '@/api/settings';
import styles from './SynonymsModal.module.css';

interface SynonymsModalProps {
  isOpen: boolean;
  onClose: () => void;
  field: FieldRegistryEntry | null;
}

export function SynonymsModal({ isOpen, onClose, field }: SynonymsModalProps) {
  const synonyms = field?.synonyms ?? [];
  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={`Synonyms for ${field?.field_name ?? ''}`}
      size="md"
      showCloseButton
      closeOnBackdrop
    >
      <p className={styles.intro}>
        Auto-generated aliases that resolve to this field in Explorer search.
        Read-only — regenerated by the field's <strong>Regen</strong> action or
        by <strong>Regenerate All</strong>.
      </p>
      {synonyms.length === 0 ? (
        <p className={styles.empty}>No synonyms for this field.</p>
      ) : (
        <div className={styles.chipList}>
          {synonyms.map((s) => (
            <span key={s} className={styles.chip}>{s}</span>
          ))}
        </div>
      )}
    </Modal>
  );
}
